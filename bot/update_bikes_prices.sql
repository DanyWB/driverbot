DELETE FROM bike_prices bp
USING bikes b
LEFT JOIN src_bikes s ON lower(trim(b.name)) = lower(trim(s.name))
WHERE bp.bike_id = b.id
  AND s.name IS NULL
  AND NOT EXISTS (
    SELECT 1
    FROM rentals r
    WHERE r.bike_id = b.id
  );

