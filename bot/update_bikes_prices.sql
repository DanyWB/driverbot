CREATE TEMP TABLE calc_prices AS
SELECT
  b.id AS bike_id,
  s.season_id,
  s.days_type,
  ROUND(s.total_price::numeric / s.days_count, 2) AS price_per_day
FROM src_prices s
JOIN bikes b ON lower(trim(b.name)) = lower(trim(s.name));

-- Update existing price rows
UPDATE bike_prices bp
SET price_per_day = cp.price_per_day
FROM calc_prices cp
WHERE bp.bike_id = cp.bike_id
  AND bp.season_id = cp.season_id
  AND bp.days_type = cp.days_type;

-- Insert missing price rows
INSERT INTO bike_prices (bike_id, season_id, days_type, price_per_day)
SELECT cp.bike_id, cp.season_id, cp.days_type, cp.price_per_day
FROM calc_prices cp
LEFT JOIN bike_prices bp
  ON bp.bike_id = cp.bike_id AND bp.season_id = cp.season_id AND bp.days_type = cp.days_type
WHERE bp.id IS NULL;

