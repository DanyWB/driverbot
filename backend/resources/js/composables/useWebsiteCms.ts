export function useWebsiteCms() {
    const { locale } = useLocale();
    function ct(message: string): string {
        return locale.value === 'ru'
            ? (ru[message] ?? englishLabels[message] ?? message)
            : (englishLabels[message] ?? message);
    }

    return { ct, locale };
}
